async def ensure_schema(db):
    """Ensure tg_import_jobs table and triggers exist; reset stalled running jobs on boot."""
    await db.execute("""
        CREATE TABLE IF NOT EXISTS tg_import_jobs (
            id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            link          TEXT NOT NULL,
            target_chat   TEXT NOT NULL,
            target_msg_id BIGINT NOT NULL,
            chat_id       BIGINT,
            message_id    BIGINT,
            filename      TEXT,
            title         TEXT,
            tags          TEXT,
            size          BIGINT NOT NULL DEFAULT 0,
            status        TEXT NOT NULL DEFAULT 'queued'
                            CHECK (status IN ('queued','running','downloading','downloaded','uploading','done','failed','cancelled')),
            progress      INTEGER NOT NULL DEFAULT 0,
            speed         TEXT,
            error         TEXT,
            upload_id     BIGINT,
            created_at    TEXT NOT NULL DEFAULT now_text(),
            updated_at    TEXT NOT NULL DEFAULT now_text()
        )
    """)
    await db.execute("CREATE INDEX IF NOT EXISTS idx_tg_import_jobs_status ON tg_import_jobs(status)")
    await db.execute("""
        CREATE OR REPLACE FUNCTION notify_tg_import_change() RETURNS trigger
        LANGUAGE plpgsql AS $func$ BEGIN
        PERFORM pg_notify('tg_import_changed', TG_TABLE_NAME); RETURN NULL; END $func$
    """)
    await db.execute("DROP TRIGGER IF EXISTS trg_notify_tg_import_jobs ON tg_import_jobs")
    await db.execute("""
        CREATE TRIGGER trg_notify_tg_import_jobs AFTER INSERT OR UPDATE OR DELETE ON tg_import_jobs
        FOR EACH STATEMENT EXECUTE FUNCTION notify_tg_import_change()
    """)
    await db.execute("""
        UPDATE tg_import_jobs
        SET status='queued', progress=0, updated_at=now_text()
        WHERE status IN ('running', 'downloading')
    """)


