"""Telegram Message Link Import worker & handlers (Telethon MTProto).

Allows authorized users to import videos/files from public or private Telegram channels
(including restricted channels with `noforwards` / Restrict Saving Content enabled) by
pasting the message link (e.g. `https://t.me/c/1234567890/42` or `https://t.me/channel/42`).

Runs the MTProto worker inside the watcher process (shares the Telethon worker.session).
The bot process inserts rows into `tg_import_jobs`, sends the initial progress message,
and the watcher worker downloads the media (including multi-file albums/media groups)
via Telethon MTProto chunk stream, saves it to staging, and hands it off to `upload_jobs`
to be uploaded to the user's storage channel.
"""

import asyncio
import html
import os
import re
import shutil
import time
from typing import List, Optional, Tuple

import httpx
from telethon.errors import FloodError

from bot_config import (
    BOT_TOKEN,
    DRIVE_SPLIT_PART_MB,
    PIKPAK_MAX_BYTES,
    PIKPAK_STAGING_DIR,
    TELEGRAM_API_URL,
    log,
)
from tg_helpers import parse_caption

POLL_INTERVAL = 3
PROGRESS_THROTTLE_S = 4.0
DB_THROTTLE_S = 5.0

_MEDIA_EXTS = {
    ".mp4", ".mkv", ".avi", ".mov", ".wmv", ".flv", ".webm", ".m4v", ".ts", ".3gp",
    ".jpg", ".jpeg", ".png", ".gif", ".webp", ".mp3", ".m4a", ".flac", ".wav", ".ogg",
}

TG_LINK_RE = re.compile(
    r"(?:https?://)?t\.me/(?:c/(\d+)|([a-zA-Z0-9_]+))/(?:(\d+)/)?(\d+)(?:-(\d+))?"
)


class TgImportError(Exception):
    """User-facing import failure message."""


def human_size(n) -> str:
    n = float(n or 0)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.0f} {unit}" if unit in ("B", "KB") else f"{n:.2f} {unit}"
        n /= 1024
    return f"{n:.2f} TB"


def _fmt_eta(secs: float) -> str:
    secs = int(secs)
    if secs >= 3600:
        return f"{secs // 3600}h {secs % 3600 // 60}m"
    if secs >= 60:
        return f"{secs // 60}m {secs % 60}s"
    return f"{secs}s"


def _is_media(fname: str) -> bool:
    return os.path.splitext(fname)[1].lower() in _MEDIA_EXTS


def parse_tg_links(text: str) -> List[dict]:
    """Parse text for Telegram message links. Returns list of parsed targets."""
    results = []
    seen = set()
    for m in TG_LINK_RE.finditer(text):
        raw_c = m.group(1)
        username = m.group(2)
        if raw_c:
            target_chat = f"-100{raw_c}"
        else:
            target_chat = username

        start_msg_id = int(m.group(4))
        end_msg_id = int(m.group(5)) if m.group(5) else start_msg_id

        if end_msg_id < start_msg_id:
            end_msg_id = start_msg_id
        end_msg_id = min(end_msg_id, start_msg_id + 50)

        for mid in range(start_msg_id, end_msg_id + 1):
            key = (target_chat, mid)
            if key not in seen:
                seen.add(key)
                results.append({
                    "target_chat": target_chat,
                    "target_msg_id": mid,
                    "raw_link": m.group(0),
                })
    return results


def parse_import_command(text: str) -> Tuple[List[dict], Optional[str], Optional[str]]:
    """Parse /import command line.

    Syntax: /import <link> [Custom Title] [| tag1, tag2]
    Returns (targets, custom_title, custom_tags).
    """
    cleaned = text.strip()
    for prefix in ("/import", "/save", "/dl", "/link"):
        if cleaned.lower().startswith(prefix):
            cleaned = cleaned[len(prefix):].strip()
            break

    links = parse_tg_links(cleaned)
    if not links:
        return [], None, None

    leftover = TG_LINK_RE.sub("", cleaned).strip()
    title = None
    tags = None

    if leftover:
        if "|" in leftover:
            parts = leftover.split("|", 1)
            title = parts[0].strip() or None
            tags = ", ".join(t.strip() for t in parts[1].split(",") if t.strip()) or None
        else:
            title = leftover.strip() or None

    return links, title, tags


